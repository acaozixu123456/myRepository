const sourceTotal = (r: ReturnType<typeof runIncomeScenario>, source: string): Quantities => {
  const total: Quantities = {};
  for (const d of r.days) for (const [id, count] of Object.entries(d.sources[source] ?? {})) total[id] = (total[id] ?? 0) + count;
  return total;
};
const runner = fileURLToPath(new URL('../tools/run-economy-paid.mjs', import.meta.url));
const project = fileURLToPath(new URL('..', import.meta.url));

describe('paid economy audit actual resource accounting', () => {
  let report: EconomyPaidReport;
  beforeAll(() => { report = runEconomyPaid(); });

  it('prices only explicit anchors and keeps EXP, moon, unknown values and variable yarn visible', () => {
    expect(valueIncome({ fish: 100, bells: 2, catnip_small: 4, paw_seal: 3, exp: 999, moon: 25, yarn_small: 2, unknown: 7 })).toEqual({
      pricedFish: 1900, unpriced: { exp: 999, moon: 25, yarn_small: 2, unknown: 7 },
    });
    const p = newPlayer(DEFAULT_START);
    p.res.catnip = 1.5; p.res.tickets = 2; p.inventory.items.paw_seal = 10;
    expect(balances(p)).toMatchObject({ catnip_small: 1.5, recruit_ticket: 2, paw_seal: 10 });
    expect(balances(p).catnip).toBeUndefined(); expect(balances(p).tickets).toBeUndefined();
  });

  it('runs seven real sign-in days without multiplying a weekly reward into seven daily grants', () => {
    const free = report.scenarios.find((s) => s.ordinal === 1 && s.baseVip === 0 && !s.monthly)!;
    expect(sourceTotal(free, 'signin')).toEqual({ fish: 8000, bells: 420, catnip_small: 8, recruit_ticket: 13, moon: 100 });
    expect(free.days[6].sources.signin).toEqual({ recruit_ticket: 10, moon: 100 });
    expect(sourceTotal(free, 'idle')).toEqual({ fish: 34560 * 7, exp: 17280 * 7 });
    expect(sourceTotal(free, 'fast')).toEqual({ fish: 2880 * 7, exp: 1440 * 7 });
    expect(sourceTotal(free, 'arena')).toEqual({ paw_seal: 24 * 40 + 11 * 15 });
  });

  it('claims only goals generated by the actual activity trace and grants each weekly target once', () => {
    const free = report.scenarios.find((s) => s.ordinal === 1 && s.baseVip === 0 && !s.monthly)!;
    expect(sourceTotal(free, 'quests')).toEqual({ fish: 63400, exp: 12100, bells: 290, catnip_small: 35, paw_seal: 720, fishbone_medium: 3, yarn_small: 2 });
    const ids = free.days.flatMap((d) => d.claimed);
    for (const id of ['daily_login', 'daily_idle', 'daily_campaign', 'daily_arena', 'daily_friend']) expect(ids.filter((x) => x === id)).toHaveLength(7);
    for (const id of ['weekly_campaign', 'weekly_idle', 'weekly_arena']) expect(ids.filter((x) => x === id)).toHaveLength(1);
    expect(ids).not.toContain('daily_recruit'); expect(ids).not.toContain('daily_growth'); expect(ids).not.toContain('daily_tower');
    expect(ids.every((id) => QUESTS.some((q) => q.id === id && ['daily', 'weekly'].includes(q.kind)))).toBe(true);
  });

  it('uses real VIP rounding, full sign-in doubling and the correct extra free exploration counts', () => {
    const s3 = report.scenarios.find((s) => s.ordinal === 1 && s.baseVip === 3 && !s.monthly)!;
    expect(sourceTotal(s3, 'signin')).toEqual({ fish: 16000, bells: 840, catnip_small: 16, recruit_ticket: 26, moon: 200 });
    expect(sourceTotal(s3, 'vip')).toEqual({ bells: 2100, moon: 420 });
    const s8 = report.scenarios.find((s) => s.ordinal === 1 && s.baseVip === 8 && !s.monthly)!;
    expect(s8.freeFast).toBe(3); expect(s8.averageSources.fast.fish).toBeCloseTo(3 * 120 * 30);
    expect(s8.averageSources.fast.exp).toBeCloseTo(3 * 120 * 15);
    expect(report.scenarios.find((s) => s.ordinal === 1 && s.baseVip === 12 && !s.monthly)!.freeFast).toBe(4);
  });

  it('accounts for the real VIP0-to-VIP2 month-card upgrade while excluding its instantaneous 300 moon', () => {
    const card = report.scenarios.find((s) => s.ordinal === 1 && s.baseVip === 0 && s.monthly)!;
    expect(card.effectiveVip).toBe(2); expect(card.cumulativeYuan).toBe(30); expect(card.instantaneousMoon).toBe(300);
    expect(sourceTotal(card, 'card')).toEqual({ bells: 700, moon: 700 });
    expect(sourceTotal(card, 'vip')).toEqual({ bells: 1400, moon: 280 });
    expect(card.average.moon).toBeCloseTo((700 + 280 + 100) / 7);
  });

  it('keeps the 24h single-login cache limit separate and values weekly yarn by actual use at that stage', () => {
    expect(report.offline.find((o) => o.ordinal === 1 && o.vip === 0)).toMatchObject({ capHours: 8, capturedHours: 8, fish: 11520, exp: 5760 });
    expect(report.offline.find((o) => o.ordinal === 1 && o.vip === 12)).toMatchObject({ capHours: 14, capturedHours: 14, fish: 27720, exp: 13440 });
    expect(report.offline.find((o) => o.ordinal === 144 && o.vip === 12)!.capturedHours).toBe(24);
    expect(report.yarnUses.find((y) => y.ordinal === 1 && y.vip === 0)).toEqual({ ordinal: 1, vip: 0, count: 2, minutes: 120, fish: 2880, exp: 1440 });
    expect(report.yarnUses.find((y) => y.ordinal === 144 && y.vip === 0)!.fish).toBe(71520);
  });

  it('covers all required snapshots, current tiers and NPCs with deterministic finite outputs', () => {
    expect(report.scenarios).toHaveLength(32); expect(report.tiers).toHaveLength(5); expect(report.npcs).toHaveLength(NPCS.length);
    expect(report.tiers.map((t) => t.unlockOrdinal)).toEqual([1, 18, 42, 72, 110]);
    expect(report.questCeilings.map((q) => q.available)).toEqual([12, 8]);
    expect(report.costs.find((c) => c.ordinal === 144)).toMatchObject({ level: 95, referenceStar: 5, minimumStar: 4, fish: 3050800, exp: 6110300, dedicatedShards: 1650 });
    expect(report.gifts.find((g) => g.count === 7)!.valuation.pricedFish).toBe(7 * (400 * 100 + 2 * 30000));
    expect(report.gifts.find((g) => g.count === 30)!.valuation.pricedFish).toBe(30 * (400 * 100 + 2 * 30000));
    const checkFinite = (value: unknown): void => {
      if (typeof value === 'number') { expect(Number.isFinite(value)).toBe(true); expect(value).toBeGreaterThanOrEqual(0); }
      else if (value && typeof value === 'object') for (const [key, child] of Object.entries(value)) if (key !== 'gain' && key !== 'joinDay') checkFinite(child);
    };
    checkFinite(report);
    expect(runEconomyPaid()).toEqual(report);
  });

  it('renders the partial valuation, raw materials, causal limits, reproducible baseline and supplied SP summary', () => {
    const text = renderEconomyPaid(report, 'test-revision', '独立SP报告摘要：1/2/3 SP，实际样本。');
    for (const fragment of ['test-revision', '2026-10-05', '未定价', '35场24胜', '05:00', 'EXP', '月光珠', '每天一次', 'SP_BALANCE_PAID.md', '专属碎片']) expect(text).toContain(fragment);
    expect(text).toContain('独立SP报告摘要：1/2/3 SP，实际样本。');
    expect(text).toContain('2.06'); expect(text).toContain('2.11'); expect(text).toContain('EXP计价口径提案');
  });
});

describe('economy audit independent mechanical fixtures', () => {
  it('proves one clear plus two sweeps share the daily three-attempt cap instead of adding rewards twice', () => {
    const p = newPlayer(DEFAULT_START), before = balances(p);
    expect(dungeonStart(p, 'fish', 1, DEFAULT_START).ok).toBe(true); dungeonWin(p, 'fish', 1, DEFAULT_START);
    expect(dungeonSweep(p, 'fish', 1, DEFAULT_START).ok).toBe(true); expect(dungeonSweep(p, 'fish', 1, DEFAULT_START).ok).toBe(true);
    expect(dungeonLeft(p, 'fish', DEFAULT_START)).toBe(0); expect(p.res.fish - before.fish).toBe(27000);
    const snapshot = structuredClone(p);
    expect(dungeonSweep(p, 'fish', 1, DEFAULT_START).ok).toBe(false); expect(p).toEqual(snapshot);
    expect(dungeonLeft(p, 'fish', DEFAULT_START + DAY)).toBe(3);
  });

  it('characterizes K=24 from equal-rating actual outcomes and caps seven-day free matches', () => {
    const now = DEFAULT_START + 12 * 3600000;
    const win = newPlayer(now), lose = newPlayer(now), rival = NPCS[0];
    ensureSocial(win).arena.rating = npcRating(rival, now); ensureSocial(lose).arena.rating = npcRating(rival, now);
    expect(arenaFinish(win, rival.id, true, now).delta).toBe(12); expect(arenaFinish(lose, rival.id, false, now).delta).toBe(-12);
    const result = arenaTrajectory('nearest', 1);
    expect(result.days.reduce((n, d) => n + d.wins + d.losses, 0)).toBe(35);
    expect(result.days.every((d) => d.wins === 5 && d.losses === 0 && d.gain > 0)).toBe(true);
    expect(result.finalRating).toBeLessThanOrEqual(1840);
  });

  it('distinguishes midnight activity resets from the quest 05:00 boundary', () => {
    const p = newPlayer(DEFAULT_START + 6 * 3600000);
    track(p, 'login');
    const beforeMidnight = DEFAULT_START + DAY - 1, afterMidnight = DEFAULT_START + DAY;
    expect(dayIndex(afterMidnight) - dayIndex(beforeMidnight)).toBe(1);
    expect(rollover(p, afterMidnight)).toBe(false); expect(p.quests.progress.daily_login).toBe(1);
    expect(rollover(p, afterMidnight + 5 * 3600000)).toBe(true); expect(p.quests.progress.daily_login).toBeUndefined();
    expect(arenaLeft(p, afterMidnight)).toBe(5);
  });

  it('actually acquires specific shards before crossing level caps in the reproducible no-SP growth trace', () => {
    const a = runGrowthScenario(0, 123), b = runGrowthScenario(0, 123);
    expect(a).toEqual(b); expect(a.points.map((p) => p.day)).toEqual([1, 7, 30]);
    expect(a.points[2].pulls).toBeGreaterThan(0);
    for (const point of a.points) point.levels.forEach((level, index) => {
      expect(point.stars[index]).toBeGreaterThanOrEqual(1); expect(point.stars[index]).toBeLessThanOrEqual(5);
      expect(level).toBeLessThanOrEqual(heroLevelCap(point.stars[index]));
    });
    expect(a.points[2].power).toBeGreaterThan(a.points[0].power);
  });

  it('rejects invalid scenarios and exposes CLI help, invalid arguments and deterministic JSON', () => {
    for (const options of [{ seed: 0 }, { seed: NaN }, { start: DEFAULT_START + DAY }]) expect(() => runEconomyPaid(options)).toThrow();
    expect(() => runIncomeScenario(145, 1, 0, false)).toThrow(); expect(() => runIncomeScenario(1, 1, 13, false)).toThrow();
    const help = execFileSync(process.execPath, [runner, '--help'], { cwd: project, encoding: 'utf8' });
    expect(help).toContain('--json');
    const invalid = spawnSync(process.execPath, [runner, '--seed', '0'], { cwd: project, encoding: 'utf8' });
    expect(invalid.status).toBe(1);
    const report = JSON.parse(execFileSync(process.execPath, [runner, '--json', '--seed', '123'], { cwd: project, encoding: 'utf8' }));
    expect(report.seed).toBe(123); expect(report.scenarios).toHaveLength(32); expect(report.timezone).toBe('UTC');
  });
});
